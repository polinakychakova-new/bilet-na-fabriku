def diff_zone(ok, bad):
    """Ровно одна правка (замена, лишняя или пропущенная буква). Возвращает зону (0-based индексы в bad) или None."""
    if ok == bad: return None
    i = 0
    while i < min(len(ok), len(bad)) and ok[i] == bad[i]: i += 1
    if len(ok) == len(bad):
        return [i] if ok[i+1:] == bad[i+1:] else None
    if len(bad) == len(ok) + 1:               # лишняя буква
        return [i] if ok[i:] == bad[i+1:] else None
    if len(bad) + 1 == len(ok):               # пропущена буква → обе соседние
        if ok[i+1:] != bad[i:]: return None
        z = [j for j in (i-1, i) if 0 <= j < len(bad) and bad[j] != ' ']
        return z
    return None

def main(out_dir):
    errors, data = [], []
    for grade, rows, need in ((1,G1,100),(2,G2,100),(3,G3,100),(4,G4,100)):
        if len(rows) != need: errors.append(f"класс {grade}: {len(rows)} записей, нужно {need}")
        seen = set()
        for n,(ok,rule,wrongs) in enumerate(rows,1):
            if ok in seen: errors.append(f"класс {grade}: повтор «{ok}»")
            seen.add(ok)
            words = len(ok.split())
            if grade <= 2 and words != 1: errors.append(f"класс {grade}: «{ok}» не одно слово")
            if grade >= 3 and words < 2: errors.append(f"класс {grade}: «{ok}» не словосочетание")
            ws = []
            for w in wrongs:
                z = diff_zone(ok, w)
                if not z: errors.append(f"класс {grade}: «{ok}» → «{w}»: не ровно одна ошибка"); continue
                # ошибка должна быть внутри одного слова
                wi = {w[:k].count(' ') for k in z}
                if len(wi) != 1: errors.append(f"класс {grade}: «{w}»: зона на границе слов")
                ws.append({"text": w, "zone": z})
            data.append({"id": f"g{grade}-{n:03d}", "grade": grade, "text": ok, "rule": rule, "wrong": ws})
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir,"words.json"),"w",encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    with open(os.path.join(out_dir,"words.csv"),"w",encoding="utf-8-sig",newline="") as f:
        wr = csv.writer(f, delimiter=";")
        wr.writerow(["Класс","№","Правильно","Правило","Ошибочные варианты (зона = номер буквы)"])
        for d in data:
            wr.writerow([d["grade"], d["id"][-3:].lstrip("0"), d["text"], d["rule"],
                         "; ".join(f'{w["text"]} → {"–".join(str(k+1) for k in w["zone"])}' for w in d["wrong"])])
    print("Записей:", len(data))
    for g in (1,2,3,4):
        rules = {}
        for d in data:
            if d["grade"]==g: rules[d["rule"]] = rules.get(d["rule"],0)+1
        print(f"Класс {g}:", rules)
    print("ОШИБКИ:" if errors else "Проверка пройдена: ошибок нет", *errors, sep="\n  ")
    return 1 if errors else 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "data"))
